#!/usr/bin/env python3
"""Insulation domains as KiCad net classes and DRC rules (run under tools/p2k/bin/kipy; since v4
fix 16, 2026-11-05).

The pours have no cut-outs any more (fix 16): KiCad's zone filler keeps every pour clear of other
copper by the clearance rules. The IEC 61010-1 gaps between the domains of tools/v4/domains.py
(P <-> I reinforced 5.0 mm, P/I <-> E basic 2.5 mm, STATUS.md "v4 fix 13/14") become:
  - net classes DOM_P / DOM_I / DOM_E (copies of Default) in kicad/ac_psu.kicad_pro, assigned by
    netclass_patterns, one exact net name per pattern (nets of no domain stay Default);
  - kicad/ac_psu.kicad_dru: clearance rules between the classes (zone fill and DRC).
The patterns are regenerated from the schematic netlist, so a schematic change that moves a net to
another domain (or renames it) shows up in --check.

Usage: tools/p2k/bin/kipy tools/v4/domain_rules.py [--check]
"""
import copy
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import board_common as bc  # noqa: E402
import domains  # noqa: E402

PRO = os.path.join(bc.ROOT, "kicad", "ac_psu.kicad_pro")
DRU = os.path.join(bc.ROOT, "kicad", "ac_psu.kicad_dru")
CLASS = {"P": "DOM_P", "I": "DOM_I", "E": "DOM_E"}


def dru_text():
    out = ["(version 1)",
           "# Generated by tools/v4/domain_rules.py - do not edit. IEC 61010-1 insulation spacing",
           "# between the domains of tools/v4/domains.py (copper to copper on each layer; zone fills",
           "# keep these gaps automatically)."]
    for (a, b), gap in sorted(((tuple(sorted(k)), v) for k, v in domains.GAP.items())):
        ca, cb = CLASS[a], CLASS[b]
        kind = "reinforced" if gap >= 5 else "basic"
        out += ["",
                f'(rule "{a}-{b} {kind} {gap:.1f} mm"',
                f"  (constraint clearance (min {gap:.1f}mm))",
                f"  (condition \"(A.NetClass == '{ca}' && B.NetClass == '{cb}') || "
                f"(A.NetClass == '{cb}' && B.NetClass == '{ca}')\"))"]
    return "\n".join(out) + "\n"


def pro_text(dom):
    with open(PRO) as f:
        pro = json.load(f)
    ns = pro["net_settings"]
    default = next(c for c in ns["classes"] if c["name"] == "Default")
    classes = [default]
    for n, (d, name) in enumerate(sorted(CLASS.items())):
        c = copy.deepcopy(default)
        c["name"] = name
        c["priority"] = n
        classes.append(c)
    ns["classes"] = classes
    ns["netclass_patterns"] = [{"netclass": CLASS[d], "pattern": net}
                               for net, d in sorted(dom.items()) if d]
    return json.dumps(pro, indent=2) + "\n"


def main():
    _, nets = bc.export_netlist()
    dom = domains.classify(nets)
    want = {PRO: pro_text(dom), DRU: dru_text()}
    stale = []
    for path, text in want.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, bc.ROOT))
            if "--check" not in sys.argv:
                with open(path, "w") as f:
                    f.write(text)
    count = {d: sum(1 for v in dom.values() if v == d) for d in CLASS}
    print(f"domain_rules: {count['P']} nets DOM_P, {count['I']} DOM_I, {count['E']} DOM_E, "
          f"{sum(1 for v in dom.values() if not v)} without domain")
    if "--check" in sys.argv:
        # the board must resolve every net to its class (pattern matching is KiCad's)
        import pcbnew
        board = pcbnew.LoadBoard(bc.BOARD)
        bad = []
        for net, d in dom.items():
            ni = board.FindNet(net)
            if ni is not None and ni.GetNetClassName() != CLASS.get(d, "Default"):
                bad.append(f"{net}: {ni.GetNetClassName()} (want {CLASS.get(d, 'Default')})")
        for x in stale:
            print(f"domain_rules: {x} is out of date (run tools/p2k/bin/kipy tools/v4/domain_rules.py)")
        for x in bad[:20]:
            print(f"domain_rules: net class {x}")
        print("domain_rules: " + ("OK" if not stale and not bad else "FAILED"))
        sys.exit(1 if stale or bad else 0)
    print("domain_rules: wrote " + (", ".join(stale) if stale else "nothing (up to date)"))


if __name__ == "__main__":
    main()
