#!/usr/bin/env python3
"""Routing list of the card area (V5_LAYOUT_PLAN.md phase 4): every net with an open connection, from the
DRC report (reports/drc.json, written by tools/drc.py) and the board, grouped for the routing brief.

  tools/p2k/bin/kipy tools/v5/routing_list.py      -> reports/v5_layout/routing_list.md
"""
import collections
import json
import os
import re
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path[:0] = [HERE, TOOLS, os.path.join(TOOLS, "v4")]
import board_common as bc  # noqa: E402
import card_layout as L  # noqa: E402
import domains  # noqa: E402
from layout_proposal import inside  # noqa: E402

T = pcbnew.ToMM
GROUPS = [   # (title, test(net), special needs)
    ("1. Sigma-delta clock and data (ISO side, U21 -> U4 / U6)", lambda n: n in ("INU_ADCLK", "MDATA_INU", "ADCLK_DAB", "MDATA_DAB"),
     "Clock and data of one modulator side by side, same layer (In3), same length within about 5 mm, away from the PWM "
     "bundle. U4 is west of J11: the pair goes north of J11 at y >= 51.1 on In3."),
    ("2. Divider taps and the measurement chain (ISO side)", lambda n: n.startswith(("Net-(U7", "Net-(U2", "Net-(C10")) or
     re.fullmatch(r"ISOADA\d(_AIN)?|REF_1V65_ISO", n), "High impedance (10k with 1 nF at the op amp). The six taps come from "
     "R67/R68/R71/R82/R85/R256 at x -15..-2: route them on In3 under the ISOGND plane, not next to the PWM bundle, "
     "not through the DC bus band on F.Cu/B.Cu."),
    ("3. PWM bundle and relay (ISO side, U19/U20 -> J4/J6/J8)", lambda n: re.fullmatch(r"PWM_Q\d|PWM_TRANS[456]|DAB_PWM_(HI|LO)_SEC|GPIO_BYPASS_RLY_ISO", n),
     "From the isolator pins (B.Cu, y 39..41) one via each, then In3 under the DC bus band to the through-hole pin "
     "of J4/J6/J8. No vias and no F.Cu/B.Cu tracks in the band y 43.2..48.8. Channels of U19/U20 may be swapped."),
    ("4. CTRL piece at J11: J11 fan-out", lambda n: n.endswith(("_CTRL", "_ISO", "_ISOLATED")) or n in ("ADCLK_ISO", "MDATA_ISO"),
     "J11 pins to the CTRL pins of U13/U15/U16 (top) and U19-U21 (bottom). F.Cu, B.Cu, In3. Nothing leaves the area."),
    ("5. CTRL piece at J11: analog chain and supply", lambda n: re.fullmatch(r"ISOADA\d_(N|P|M|PL|OUT)|OPA_SPARE|CTRL_NR|5V_CTRL_A|3V3_CTRL|CTRLGND_A", n),
     "AMC1311 outputs to the difference amplifiers are differential pairs (N/P): short, side by side. 3V3_CTRL and "
     "CTRLGND_A: one via per pad to the planes (In2 / In1+In4). PEC1 to the CTRLGND_A planes with a track >= 1.5 mm wide "
     "(protective bond, CTRL_ISOLATION_PLAN.md 7.3)."),
    ("6. CTRL piece at J12: buck converter", lambda n: n.startswith("CTRL_") or n in ("5V_CTRL", "CTRLGND"),
     "CTRL_W -> D16 -> CTRL_RAW (C138 right under D16) and CTRL_SW (U28 pin 2 -> L2): short and wide (>= 1 mm). "
     "CTRL_FB away from CTRL_SW and L2. 5V_CTRL and CTRLGND to the planes with several vias; PEC2 >= 1.5 mm wide."),
    ("7. Primary side of U16", lambda n: re.fullmatch(r"PWM_G\d|DAB_PWM_PRI_(HI|LO)|VCC|GND", n),
     "U16 pins 9-16 to the existing primary routing (track ends near x 62..68, y -19..0). F.Cu / B.Cu / In3 inside the "
     "primary area only."),
    ("8. ISO supplies", lambda n: n in ("3V3_ISO", "ISOGND", "5V_ISOL", "15V_ISO", "ISOPGND"),
     "3V3_ISO / ISOGND: one via per pad to the planes. 5V_ISOL: U8 pin 3 (91, -20) -> U10 (97, -2) and on to J4/J6/J8 pin 45 "
     "(>= 0.8 mm, about 1 A), inside the ISO area, not through the J12 piece."),
]


def main():
    d = json.load(open(os.path.join(bc.REPORTS, "drc.json")))
    board = pcbnew.LoadBoard(bc.BOARD)
    _, nets = bc.export_netlist()
    dom = domains.classify(nets)
    pads = collections.defaultdict(list)
    for fp in board.GetFootprints():
        for p in fp.Pads():
            n = domains.short(p.GetNetname())
            x, y = T(p.GetPosition().x), -T(p.GetPosition().y)
            pads[n].append((fp.GetReference(), p.GetNumber(), x, y, "THT" if p.GetDrillSize().x > 0 else ("B" if fp.IsFlipped() else "F")))
    opens = collections.Counter()
    for u in d["unconnected_items"]:
        m = re.search(r"\[([^\]]*)\]", u["items"][0]["description"])
        if m:
            opens[m.group(1)] += 1
    full = {domains.short(n): n for n in nets}
    out = ["# Routing list of the card area (v5 step 4)", "",
           "Generated by `tools/v5/routing_list.py` from `reports/drc.json` and the board. One row per net with an open "
           "connection: the number of missing connections (for GND, ISOGND, 15V_ISO and VCC the count includes the aux flyback) and every pad of the net (ref-pin, x, y in IPC mm, side: "
           "F / B / THT). Read with `routing_brief.md`.", ""]
    done, total = set(), 0
    scope = lambda n: any(r in L.PLACE or (L.CARD[0] < x < L.CARD[2] and L.CARD[1] - 16 < y < L.CARD[3] + 8) for r, _, x, y, _ in pads[n]) and \
        (n in ("GND", "ISOGND", "15V_ISO", "VCC") or not any(y < -84 for _, _, _, y, _ in pads[n]))
    for title, test, needs in GROUPS:
        rows = [(n, c) for n, c in sorted(opens.items()) if n not in done and test(n) and scope(n)]
        if not rows:
            continue
        out += [f"## {title}", "", needs, "", "| Net | Domain | Open | Pads |", "|---|---|---|---|"]
        for n, c in rows:
            done.add(n)
            total += c
            ps = sorted(pads[n], key=lambda p: (p[2], p[3]))
            txt = ", ".join(f"{r}-{pin} ({x:.1f}, {y:.1f}) {s}" for r, pin, x, y, s in ps[:14]) + (f", ... {len(ps)} pads" if len(ps) > 14 else "")
            out.append(f"| {n} | {dom.get(full.get(n, n)) or '-'} | {c} | {txt} |")
        out.append("")
    rest = [(n, c) for n, c in sorted(opens.items()) if n not in done]
    inscope = [(n, c) for n, c in rest if scope(n)]
    if inscope:
        out += ["## 9. Other nets in the card area", "", "| Net | Domain | Open | Pads |", "|---|---|---|---|"]
        for n, c in inscope:
            total += c
            ps = sorted(pads[n], key=lambda p: (p[2], p[3]))
            out.append(f"| {n} | {dom.get(full.get(n, n)) or '-'} | {c} | " + ", ".join(f"{r}-{pin} ({x:.1f}, {y:.1f}) {s}" for r, pin, x, y, s in ps[:14]) + " |")
        out.append("")
    out += ["## 10. DC bus past J11 (open decision, not for the router)", "",
            "ISODC+ (B.Cu) and ISOPGND (F.Cu) are each in two pieces since v5 step 1: the pours end 5 mm from J11 on both sides, "
            "and J8 / INU_OUT2 close the corridor north of J11 (y 51.1 .. 53.5). West piece: C8 and the inverter bridge. East piece: "
            "the band y 43.2 .. 48.8 under J6, C47/C48, Q11, R64. The link needs the owner's decision (STATUS.md).", ""]
    aux = [(n, c) for n, c in rest if not scope(n)]
    out += ["## Not in this step", "",
            f"{sum(c for _, c in aux)} open connections on {len(aux)} nets belong to the aux flyback (27 parts still in the staging area) "
            "or lie outside the card area: " + ", ".join(n for n, _ in aux) + ".", ""]
    out.insert(4, f"**{total} open connections on {len(done) + len(inscope)} nets in the card area**; "
                  f"{sum(opens.values())} on the whole board.\n")
    path = os.path.join(bc.ROOT, "reports", "v5_layout", "routing_list.md")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"routing_list: {total} open connections on {len(done) + len(inscope)} card-area nets -> {os.path.relpath(path, bc.ROOT)}")


if __name__ == "__main__":
    main()
